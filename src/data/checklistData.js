/**
 * Universal checklist. Applies to every project.
 * Item ids are "<sectionId>-<position>". Append new items to the END of a list
 * so ids stay stable and saved progress keeps pointing at the same tasks.
 */
export function makeSection(id, title, icon, items, note) {
  return {
    id,
    title,
    icon,
    note,
    items: items.map((text, index) => ({ id: id + '-' + (index + 1), text })),
  };
}

